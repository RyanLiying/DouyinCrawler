"""
MediaCrawler Web Config Tool - Backend

Provides a small Flask API that:
1. Generates temporary config files (without overwriting MediaCrawler's source config)
2. Runs MediaCrawler in a subprocess with PYTHONPATH pointing to the temp config
3. Streams logs back to the browser via Server-Sent Events (SSE)
"""

