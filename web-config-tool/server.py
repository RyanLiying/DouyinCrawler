def persist_author_stat_fields(params: dict):
    """把网页勾选「作者统计（后处理）」字段持久化到 author_stats_fields.json。

    只在请求里带了 SELECTED_AUTHOR_STAT_FIELDS 时才写入；没带则不动已有文件，
    避免旧版前端或手动调用 /api/run 时意外清空选择。
    """
    if "SELECTED_AUTHOR_STAT_FIELDS" not in params:
        return
    selected = params.get("SELECTED_AUTHOR_STAT_FIELDS")
    if not isinstance(selected, list):
        return
    try:
        AUTHOR_STATS_FIELDS_FILE.write_text(
            json.dumps({"selected": selected}, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        print(f"[INFO] 已保存作者统计字段选择到 {AUTHOR_STATS_FIELDS_FILE}: {selected}")
    except Exception as e:
        print(f"[WARN] 保存作者统计字段选择失败: {e}", file=sys.stderr)


def create_temp_config(params: dict) -> tuple[Path, Path, str]:
    """Create a temporary config directory for preview/download."""
    job_id = str(uuid.uuid4())[:8]
    temp_root = Path(tempfile.gettempdir()) / f"{TEMP_CONFIG_PREFIX}{job_id}"
    temp_config_dir = temp_root / "config"

    if temp_root.exists():
        shutil.rmtree(temp_root)

    original_config = MEDIACRAWLER_DIR / "config"
    shutil.copytree(original_config, temp_config_dir)
    generate_config_files(temp_config_dir, params)

    return temp_root, temp_config_dir, job_id


# Backup helpers for the "run" path: temporarily overwrite MediaCrawler/config files
# and restore them after the crawler finishes. This avoids PYTHONPATH resolution
# issues because the script directory is always first in sys.path.
CONFIG_BACKUP_DIR = MEDIACRAWLER_DIR / "config" / ".web_config_backup"
CONFIG_FILES = ("base_config.py", "dy_config.py", "xhs_config.py")


def backup_config():
    """Backup the original config files that the tool may overwrite."""
    config_dir = MEDIACRAWLER_DIR / "config"
    CONFIG_BACKUP_DIR.mkdir(exist_ok=True)
    for name in CONFIG_FILES:
        src = config_dir / name
        if src.exists():
            shutil.copy2(src, CONFIG_BACKUP_DIR / name)


def restore_config():
    """Restore original config files from backup."""
    if not CONFIG_BACKUP_DIR.exists():
        return
    config_dir = MEDIACRAWLER_DIR / "config"
    try:
        for name in CONFIG_FILES:
            backup = CONFIG_BACKUP_DIR / name
            if backup.exists():
                shutil.copy2(backup, config_dir / name)
    except Exception as e:
        print(f"[WARN] 恢复原始配置失败: {e}", file=sys.stderr)


def apply_config(params: dict):
    """Backup and overwrite MediaCrawler config with generated config."""
    backup_config()
    generate_config_files(MEDIACRAWLER_DIR / "config", params)


def run_author_stats_enrich(queue, job):
    """爬虫成功后自动运行 tools/enrich_author_stats.py，输出逐行推入 queue（与爬虫日志同方式）。

    子进程注册到 job["process"]，与爬虫子进程同一套跟踪机制，「停止爬虫」按钮可终止它。
    后处理失败不影响已完成的爬虫结果，只在日志里打印警告和退出码。
    """
    if importlib.util.find_spec("playwright") is None:
        queue.put("[WARN] 当前环境未安装 playwright，跳过自动作者统计后处理\n")
        queue.put("[HINT] 请先 pip install playwright && playwright install chromium；"
                  "或改用 MediaCrawler 的 uv 环境手动运行: "
                  "python3 web-config-tool/tools/enrich_author_stats.py\n")
        return

    script = PROJECT_ROOT / "web-config-tool" / "tools" / "enrich_author_stats.py"
    cmd = [sys.executable, str(script)]
    queue.put(f"[INFO] 爬虫成功结束，开始自动作者统计后处理: {' '.join(cmd)}\n")
    proc = None
    try:
        proc = subprocess.Popen(
            cmd,
            cwd=str(PROJECT_ROOT),
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
        )
        # 与爬虫子进程同样注册到 job，让 /api/stop 能 terminate 它
        job["process"] = proc
        for line in proc.stdout:
            queue.put(line)
        proc.wait()
        if proc.returncode == 0:
            queue.put("[INFO] 作者统计后处理完成\n")
        elif job.get("stopped_by_user") or (proc.returncode and proc.returncode < 0):
            queue.put("[INFO] 已停止作者统计后处理\n")
        else:
            queue.put(f"[WARN] 作者统计后处理失败，退出码 {proc.returncode}；"
                      "不影响已爬取的视频数据，可检查日志后手动重跑\n")
    except Exception as e:
        queue.put(f"[WARN] 作者统计后处理启动失败: {e}；不影响已爬取的视频数据\n")
    finally:
        # 进程结束后清理，避免停止端点拿到已死进程误报「任务已结束」
        if job.get("process") is proc:
            job["process"] = None


def build_crawler_cmd(params: dict) -> list[str]:
    """根据单个平台的参数构造爬虫命令。

    仅抖音（dy）勾选了扩展字段（SELECTED_EXTRA_FIELDS）时走 enriched wrapper；
    其他平台一律走标准 main.py（xhs 勾扩展字段本就无意义）。
    """
    platform = params.get("PLATFORM", "dy")
    login_type = params.get("LOGIN_TYPE", "qrcode")
    crawler_type = params.get("CRAWLER_TYPE", "search")
    selected_extra = params.get("SELECTED_EXTRA_FIELDS", [])

    if platform == "dy" and selected_extra:
        wrapper_path = PROJECT_ROOT / "web-config-tool" / "extensions" / "run_crawler_enriched.py"
        return ["uv", "run", "--active", str(wrapper_path)]
    return [
        "uv", "run", "--active", "main.py",
        "--platform", platform,
        "--lt", login_type,
        "--type", crawler_type,
    ]


def run_single_platform(job: dict, params: dict) -> int:
    """运行单个平台的爬虫子进程，流式推送日志到 job["queue"]，返回退出码。

    运行前备份并临时覆盖 MediaCrawler/config/ 下的配置文件，运行结束（含异常）
    后在 finally 中自动恢复。
    """
    queue = job["queue"]
    cmd = build_crawler_cmd(params)
    queue.put(f"[INFO] 启动爬虫任务: {' '.join(cmd)}\n")
    returncode = -1
    try:
        apply_config(params)
        queue.put("[INFO] 已备份原配置并应用网页配置\n")

        process = subprocess.Popen(
            cmd,
            cwd=str(MEDIACRAWLER_DIR),
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
        )
        job["process"] = process

        for line in process.stdout:
            queue.put(line)

        process.wait()
        returncode = process.returncode
        if returncode == 0:
            queue.put(f"[INFO] 爬虫任务结束，退出码: {returncode}\n")
        else:
            queue.put(f"[ERROR] 爬虫任务异常结束，退出码: {returncode}\n")
    except Exception as e:
        queue.put(f"[ERROR] 启动失败: {e}\n")
    finally:
        restore_config()
        queue.put("[INFO] 已恢复 MediaCrawler/config/ 下的原始配置\n")
        # 进程结束后清理，避免停止端点拿到已死进程误报「任务已结束」
        if job.get("process") and job["process"].poll() is not None:
            job["process"] = None
    return returncode


def run_crawler(job_id: str, temp_config_dir: Path, params: dict):
    """Run MediaCrawler in a subprocess and push output to a queue.

    支持多平台串行：params 带 PLATFORMS 数组时按顺序逐个平台跑（每个平台复制
    params 并覆盖 PLATFORM）；否则按旧的单平台行为运行。小红书平台会在运行前
    自动展开输入里的 xhslink.cn 短链。

    We temporarily overwrite MediaCrawler/config/base_config.py and dy_config.py
    with the generated config, then restore the originals after the run. This is
    necessary because Python always puts the script directory first in sys.path,
    so PYTHONPATH alone cannot override MediaCrawler/config."""
    job = jobs[job_id]
    queue = job["queue"]

    platforms = params.get("PLATFORMS") or [params.get("PLATFORM", "dy")]

    queue.put(f"[INFO] 临时配置目录: {temp_config_dir}\n")
    queue.put(f"[INFO] 运行前会备份并临时覆盖 MediaCrawler/config/ 下的配置文件，运行结束后自动恢复\n")

    try:
        total = len(platforms)
        for idx, platform in enumerate(platforms, start=1):
            if job.get("stopped_by_user"):
                queue.put("[INFO] 任务已被手动停止，跳过后续平台\n")
                break

            platform_params = dict(params)
            platform_params["PLATFORM"] = platform

            # 小红书：detail/creator 列表里的 xhslink.cn 短链先展开为完整链接
            if platform == "xhs":
                for key in ("DY_SPECIFIED_ID_LIST", "DY_CREATOR_ID_LIST"):
                    value = platform_params.get(key)
                    if value and "xhslink.cn" in value:
                        platform_params[key] = resolve_xhs_shortlinks(value)

            if total > 1:
                queue.put(f"[INFO] ====== 平台 {idx}/{total}: {platform} ======\n")

            returncode = run_single_platform(job, platform_params)

            # 可选：爬虫成功结束后自动运行作者统计后处理（网页开关 AUTO_ENRICH_AUTHOR_STATS，默认关闭）
            # 仅抖音平台支持（作者统计后处理只针对抖音数据）
            if platform == "dy" and params.get("AUTO_ENRICH_AUTHOR_STATS"):
                if returncode != 0:
                    queue.put(f"[WARN] 爬虫退出码 {returncode} 非 0，跳过自动作者统计后处理；"
                              "可稍后手动运行 enrich_author_stats.py\n")
                else:
                    # 0 条数据保护：search_contents 不存在或没有数据行时不启动后处理
                    search_file = latest_search_contents(str(params.get("SAVE_DATA_PATH") or ""))
                    row_count = count_search_rows(search_file) if search_file else 0
                    if row_count > 0:
                        queue.put(f"[INFO] 检测到 {search_file} 共 {row_count} 条数据\n")
                        run_author_stats_enrich(queue, job)
                    else:
                        queue.put("[INFO] 本次未爬取到视频数据，跳过作者统计后处理\n")
    finally:
        job["finished"] = True


@app.route("/api/run", methods=["POST"])
def api_run():
    if not MEDIACRAWLER_DIR.exists():
        return jsonify({"error": f"MediaCrawler 目录不存在: {MEDIACRAWLER_DIR}"}), 400

    params = request.get_json(silent=True) or {}

    # 生成配置与启动爬虫都经过 /api/run，在这里统一持久化作者统计字段选择
    persist_author_stat_fields(params)

    try:
        temp_root, temp_config_dir, job_id = create_temp_config(params)
    except Exception as e:
        return jsonify({"error": f"生成临时配置失败: {e}"}), 500

    queue = Queue()
    jobs[job_id] = {
        "queue": queue,
        "process": None,
        "finished": False,
        "temp_config_dir": temp_config_dir,
    }

    thread = threading.Thread(target=run_crawler, args=(job_id, temp_config_dir, params), daemon=True)
    thread.start()

    return jsonify({"job_id": job_id, "temp_config_dir": str(temp_config_dir)})


@app.route("/api/stop/<job_id>", methods=["POST"])
def api_stop(job_id):
    job = jobs.get(job_id)
    if not job:
        return jsonify({"error": "任务不存在"}), 404

    process = job.get("process")
    if process and process.poll() is None:
        # 标记为用户主动停止，run_author_stats_enrich 据此打印「已停止」而不是误导性的失败/结束
        job["stopped_by_user"] = True
        process.terminate()
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            process.kill()
        job["queue"].put("[INFO] 任务已手动停止\n")
    else:
        job["queue"].put("[INFO] 任务已结束或尚未启动\n")

    job["finished"] = True
    return jsonify({"status": "stopped"})


@app.route("/api/logs/<job_id>")
def api_logs(job_id):
    job = jobs.get(job_id)
    if not job:
        return jsonify({"error": "任务不存在"}), 404

    queue = job["queue"]

    def generate():
        while True:
            try:
                line = queue.get(timeout=1)
                yield f"data: {line}\n\n"
            except Empty:
                if job["finished"]:
                    yield "event: close\ndata: done\n\n"
                    break
                yield "data: \n\n"  # keep connection alive

    return Response(generate(), mimetype="text/event-stream")


@app.route("/api/status/<job_id>")
def api_status(job_id):
    job = jobs.get(job_id)
    if not job:
        return jsonify({"error": "任务不存在"}), 404
    return jsonify({
        "finished": job["finished"],
        "running": job["process"] is not None and job["process"].poll() is None,
    })


