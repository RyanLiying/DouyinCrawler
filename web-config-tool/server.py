def latest_search_contents(save_data_path: str):
    """查找最新 search_contents 文件（csv / jsonl 都认，按修改时间取最新）。

    目录约定与 enrich 脚本的 find_latest_file 一致：
    {SAVE_DATA_PATH}/douyin/csv|jsonl/search_contents_*
    """
    root = save_data_path or DEFAULT_SAVE_DATA_PATH
    candidates = glob.glob(os.path.join(root, "douyin", "csv", "search_contents_*.csv"))
    candidates += glob.glob(os.path.join(root, "douyin", "jsonl", "search_contents_*.jsonl"))
    if not candidates:
        return None
    candidates.sort(key=lambda p: os.path.getmtime(p), reverse=True)
    return candidates[0]


def count_search_rows(path: str) -> int:
    """数 search_contents 的数据行数：csv 去掉表头，jsonl 数非空行。出错按 0 处理。"""
    try:
        if path.endswith(".jsonl"):
            with open(path, "r", encoding="utf-8") as f:
                return sum(1 for line in f if line.strip())
        with open(path, "r", encoding="utf-8-sig", newline="") as f:
            return max(sum(1 for _ in csv.reader(f)) - 1, 0)
    except Exception:
        return 0

